import AppKit
import Combine
import CryptoKit

enum ClipKind: String, Codable {
    case text, image, files
}

struct ClipItem: Identifiable, Codable, Equatable {
    var id = UUID()
    var kind: ClipKind
    /// Copied text, or file paths separated by newlines.
    var text: String?
    /// PNG file name inside the images folder.
    var imageFile: String?
    /// SHA256 of the image, used to avoid duplicates.
    var imageHash: String?
    var imageWidth: Int?
    var imageHeight: Int?
    var isScreenshot = false
    var sourceAppName: String?
    var sourceBundleID: String?
    var date = Date()

    var fileURLs: [URL] {
        (text ?? "").split(separator: "\n").map { URL(fileURLWithPath: String($0)) }
    }
}

@MainActor
final class ClipboardStore: ObservableObject {
    @Published private(set) var items: [ClipItem] = []

    let imagesDir: URL
    private let historyURL: URL
    private let settings: AppSettings
    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?
    private var cancellables = Set<AnyCancellable>()
    private let fm = FileManager.default

    /// Types password managers use to mark content that must not be recorded.
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    init(settings: AppSettings) {
        self.settings = settings
        let base = fm.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("Clipi", isDirectory: true)
        imagesDir = base.appendingPathComponent("images", isDirectory: true)
        historyURL = base.appendingPathComponent("history.json")
        try? fm.createDirectory(at: imagesDir, withIntermediateDirectories: true)
        lastChangeCount = pasteboard.changeCount

        if settings.persistHistory {
            load()
        } else {
            wipeStorage()
        }
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.3, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }

        settings.$persistHistory
            .dropFirst()
            .sink { [weak self] persist in
                guard let self else { return }
                if persist {
                    self.save(force: true)
                } else {
                    try? self.fm.removeItem(at: self.historyURL)
                }
            }
            .store(in: &cancellables)

        settings.$maxItems
            .dropFirst()
            .sink { [weak self] max in self?.trim(to: max) }
            .store(in: &cancellables)
    }

    func handleTermination() {
        if settings.persistHistory {
            save()
        } else {
            wipeStorage()
        }
    }

    // MARK: - Pasteboard monitoring

    private func poll() {
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        captureCurrentPasteboard()
    }

    private func captureCurrentPasteboard() {
        let types = pasteboard.types ?? []
        if types.contains(where: { Self.ignoredTypes.contains($0.rawValue) }) { return }

        let app = NSWorkspace.shared.frontmostApplication
        var item: ClipItem
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self],
                                             options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            item = ClipItem(kind: .files, text: urls.map(\.path).joined(separator: "\n"))
        } else if let string = pasteboard.string(forType: .string),
                  !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            item = ClipItem(kind: .text, text: string)
        } else if let png = pngDataFromPasteboard() {
            addImage(png, isScreenshot: false, sourceApp: app)
            return
        } else {
            return
        }
        item.sourceAppName = app?.localizedName
        item.sourceBundleID = app?.bundleIdentifier
        insert(item)
    }

    private func pngDataFromPasteboard() -> Data? {
        if let png = pasteboard.data(forType: .png) { return png }
        if let tiff = pasteboard.data(forType: .tiff) { return Self.pngData(from: tiff) }
        return nil
    }

    private static func pngData(from imageData: Data) -> Data? {
        guard let rep = NSBitmapImageRep(data: imageData) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }

    // MARK: - Screenshots

    func addScreenshot(at url: URL) {
        guard let raw = try? Data(contentsOf: url) else { return }
        let png = url.pathExtension.lowercased() == "png" ? raw : (Self.pngData(from: raw) ?? raw)
        // With the floating thumbnail on, the same screenshot shows up twice: first in the
        // thumbnail's temporary folder, then in the save folder. Don't clobber the clipboard again.
        let hash = Self.hash(png)
        if let existing = items.first(where: { $0.imageHash == hash }),
           existing.isScreenshot, Date().timeIntervalSince(existing.date) < 120 {
            return
        }
        writeImageToPasteboard(png)
        addImage(png, isScreenshot: true, sourceApp: nil)
    }

    // MARK: - Actions

    func copy(_ item: ClipItem) {
        pasteboard.clearContents()
        switch item.kind {
        case .text:
            pasteboard.setString(item.text ?? "", forType: .string)
        case .image:
            guard let file = item.imageFile,
                  let data = try? Data(contentsOf: imagesDir.appendingPathComponent(file)) else { return }
            writeImageToPasteboard(data)
        case .files:
            pasteboard.writeObjects(item.fileURLs as [NSURL])
        }
        lastChangeCount = pasteboard.changeCount

        // Move the item back to the top of the history
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        var moved = items.remove(at: index)
        moved.date = Date()
        items.insert(moved, at: 0)
        save()
    }

    func delete(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        removeImageFile(of: item)
        save()
    }

    func clearAll() {
        items.forEach(removeImageFile)
        items.removeAll()
        save()
    }

    // MARK: - History management

    private static func hash(_ data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }

    private func writeImageToPasteboard(_ png: Data) {
        pasteboard.clearContents()
        pasteboard.setData(png, forType: .png)
        // Some apps only read TIFF
        if let tiff = NSImage(data: png)?.tiffRepresentation {
            pasteboard.setData(tiff, forType: .tiff)
        }
        lastChangeCount = pasteboard.changeCount
    }

    private func addImage(_ png: Data, isScreenshot: Bool, sourceApp: NSRunningApplication?) {
        let hash = Self.hash(png)
        if let existing = items.firstIndex(where: { $0.imageHash == hash }) {
            var item = items.remove(at: existing)
            item.date = Date()
            item.isScreenshot = item.isScreenshot || isScreenshot
            items.insert(item, at: 0)
            save()
            return
        }
        var item = ClipItem(kind: .image, imageHash: hash, isScreenshot: isScreenshot,
                            sourceAppName: sourceApp?.localizedName,
                            sourceBundleID: sourceApp?.bundleIdentifier)
        if let rep = NSBitmapImageRep(data: png) {
            item.imageWidth = rep.pixelsWide
            item.imageHeight = rep.pixelsHigh
        }
        let fileName = "\(item.id.uuidString).png"
        do {
            try png.write(to: imagesDir.appendingPathComponent(fileName))
        } catch {
            NSLog("Clipi: could not save image: \(error)")
            return
        }
        item.imageFile = fileName
        insert(item)
    }

    private func insert(_ item: ClipItem) {
        if item.kind != .image {
            items.removeAll { $0.kind == item.kind && $0.text == item.text }
        }
        items.insert(item, at: 0)
        trim(to: settings.maxItems)
        save()
    }

    private func trim(to max: Int) {
        guard items.count > max else { return }
        items[max...].forEach(removeImageFile)
        items.removeLast(items.count - max)
        save()
    }

    private func removeImageFile(of item: ClipItem) {
        guard let file = item.imageFile else { return }
        try? fm.removeItem(at: imagesDir.appendingPathComponent(file))
    }

    // MARK: - Persistence

    private func save(force: Bool = false) {
        // force: used right after persistence is turned on (the setting isn't updated yet)
        guard settings.persistHistory || force else { return }
        do {
            let data = try JSONEncoder().encode(items)
            try data.write(to: historyURL, options: .atomic)
        } catch {
            NSLog("Clipi: could not save history: \(error)")
        }
    }

    private func load() {
        guard let data = try? Data(contentsOf: historyURL),
              let saved = try? JSONDecoder().decode([ClipItem].self, from: data) else { return }
        // Drop images whose file no longer exists
        items = saved.filter { item in
            guard let file = item.imageFile else { return true }
            return fm.fileExists(atPath: imagesDir.appendingPathComponent(file).path)
        }
    }

    private func wipeStorage() {
        try? fm.removeItem(at: historyURL)
        try? fm.removeItem(at: imagesDir)
        try? fm.createDirectory(at: imagesDir, withIntermediateDirectories: true)
    }
}
